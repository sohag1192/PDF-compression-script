input_file = (
    r"C:\Users\sohag\Downloads\Telegram Desktop\vaya dalil,kor,khotin.pdf"
)
output_file = (
    r"C:\Users\sohag\Downloads\Telegram Desktop\vaya_dalil_low_size.pdf"
)


def compress_scanned_pdf(input_path, output_path, dpi=120, quality=50):
    if not os.path.exists(input_path):
        print(f"???: ?????? ????? ?????: {input_path}")
        return

    src_doc = fitz.open(input_path)
    out_doc = fitz.open()

    orig_size = os.path.getsize(input_path) / (1024 * 1024)
    print(f"??? ?????? ????: {orig_size:.2f} MB")
    print("???????? ??? ?????, ???? ??????? ????...")

    for page_num in range(len(src_doc)):
        page = src_doc[page_num]

        # ??????? 120 DPI ?? ???? ?????? ??????? ??? (????? ????? ???? ?????? ????????)
        pix = page.get_pixmap(dpi=dpi)

        # PIL ???? ???? ??? ???
        img = Image.frombytes("RGB", [pix.width, pix.height], pix.samples)

        # ????/?????? ????-???? (Grayscale) ???? ???? ???? ??? ???
        img = img.convert("L")

        # ??????? JPEG ???????? ???????? ????? ??? ???
        buffer = io.BytesIO()
        img.save(buffer, format="JPEG", quality=quality, optimize=True)
        buffer.seek(0)

        # ???? PDF ???? ???????? ??? ???? ??? ???
        rect = page.rect
        new_page = out_doc.new_page(width=rect.width, height=rect.height)
        new_page.insert_image(rect, stream=buffer.read())

    # ???????? ????????? ???? ??? ???
    out_doc.save(output_path, garbage=4, deflate=True)
    out_doc.close()
    src_doc.close()

    new_size = os.path.getsize(output_path) / (1024 * 1024)
    saved_percent = ((orig_size - new_size) / orig_size) * 100

    print("=" * 45)
    print(f"???? ???? ???? ?????: {output_file}")
    print(f"???? ????:          {new_size:.2f} MB")
    print(f"???? ?????:         {saved_percent:.2f}%")
    print("=" * 45)


if __name__ == "__main__":
    # dpi=120 ??? quality=50 ?????? ?? ??????? ?????????? ???? ????? ???
    compress_scanned_pdf(input_file, output_file, dpi=120, quality=50)